#!/usr/bin/env python3
"""Generate docs/changelog.md from the root CHANGELOG.md.

The root CHANGELOG.md is the one place where release notes are written. The docs
site page is a generated copy, so the two cannot drift.

    python3 scripts/sync-docs-changelog.py          # write docs/changelog.md
    python3 scripts/sync-docs-changelog.py --check  # exit 1 if the page is out of date

The copy keeps the root text as it is, with two changes: a notice that the file is
generated, and any level-1 heading below the page title becomes level 3 (the 4.0.0
entry has one), so the page keeps a single H1. Standard library only.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "CHANGELOG.md"
TARGET = ROOT / "docs" / "changelog.md"

NOTICE = (
    "<!-- Generated from the root CHANGELOG.md by scripts/sync-docs-changelog.py. "
    "Do not edit this file: edit CHANGELOG.md, then run the script. -->\n"
)
FENCE = re.compile(r"^\s*(```|~~~)")


def render(source_text: str) -> str:
    """Return the docs page for the given root changelog text."""
    lines = source_text.replace("\r\n", "\n").rstrip("\n").split("\n")
    out: list[str] = []
    in_fence = False
    seen_title = False
    for line in lines:
        if FENCE.match(line):
            in_fence = not in_fence
        elif not in_fence and line.startswith("# "):
            if seen_title:
                line = "##" + line  # level 1 -> level 3
            else:
                seen_title = True
                out.extend([line, "", NOTICE.rstrip("\n")])
                continue
        out.append(line)
    if not seen_title:
        raise ValueError("CHANGELOG.md has no level-1 title")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if docs/changelog.md is out of date")
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--target", type=Path, default=TARGET)
    args = parser.parse_args(argv)

    wanted = render(args.source.read_text(encoding="utf-8"))
    if args.check:
        current = args.target.read_text(encoding="utf-8") if args.target.exists() else None
        if current != wanted:
            print(
                f"{args.target.name} does not match {args.source.name}. "
                "Run: python3 scripts/sync-docs-changelog.py",
                file=sys.stderr,
            )
            return 1
        return 0
    args.target.write_text(wanted, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
